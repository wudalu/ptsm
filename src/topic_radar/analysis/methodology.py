from __future__ import annotations

META_PROMPT = """## 话题讨论价值分析框架

分析每个话题时，从以下四个透镜判断其讨论价值.

### 透镜一：认知劫持机制
判断话题"劫持"了读者的哪种认知：
- 胡塞尔·意向性：话题是否有具体意象(人物/事件/场景)能瞬间抓住注意力？→ 悬念型话题
- 尼采·权力意志：话题是否激发优越感或反驳冲动？→ 反常识型/逆袭型/揭露型
- 列维纳斯·他者面容：话题是否让某群体产生"这就是我"的强烈认同？→ 身份共鸣型
- 福柯·话语权力：话题是否在挑战或重构某个主流叙事？→ 框架重构型
- 斯多葛·控制二分法：话题是否将焦虑从不可控转向可控行动？→ 解决方案型
- 荣格·原型叙事：话题激活了哪个深层心理原型？(见透镜二)
- 海德格尔·上手状态：话题是否低门槛、无需背景知识即可参与讨论？
- 维特根斯坦·语言游戏：话题是否容易被概括为金句或二次创作传播？

### 透镜二：荣格原型
话题激活的原型越多，讨论价值越高。每个原型对应一种心理需求：
英雄(逆袭/证明自我) | 叛逆者(反权威/打破规则) | 智者(深度洞察/解惑)
探险家(突破边界/发现自我) | 创造者(从0到1/实现愿景) | 照顾者(保护他人/责任)
魔术师(方法论/困境转化) | 情人(情感连接/关系) | 小丑(幽默解构/自嘲)
凡人(归属认同/寻找同类) | 统治者(掌控/效率秩序) | 天真者(治愈/正能量)

### 透镜三：平台讨论模式
同一话题在不同平台的讨论形态不同，据此预测评论区走向：
- 小红书 → 经验交换 + 晒图/种草 + 个人故事。高密度共鸣，情绪偏温暖实用。
- 微博 → 立场站队 + 情绪宣泄 + 阵营对喷。冲突性话题讨论量暴涨，观点极化明显。
- 抖音 → 梗扩散 + 模仿二创 + 短评刷屏。轻松/反讽类话题传播极快，但深度不足。

### 透镜四：情绪-传播联动
高讨论价值话题的共同特征：
- 触发高唤醒情绪：愤怒、焦虑、惊讶、敬畏、兴奋(低唤醒情绪如悲伤/满足传播弱)
- 具备社交货币：读者参与讨论后显得有态度、有见识、有群体归属
- 触及底层需求：生存/安全/归属类话题 > 尊重/自我实现类话题
- 利用认知偏误：锚定(具体数字冲击)、损失厌恶(不做会失去什么)、认知失调(说的vs做的差距)、从众效应(很多人已经...)

使用方法：对每个候选话题，依次用四个透镜扫描。"透镜信号"越强的话题优先级越高。

输出时，对每个推荐选题标注：
- mechanism: 触发了哪种认知劫持(来自透镜一)
- archetype: 激活了哪个原型(来自透镜二)
- discussion_forecast: 预测评论区走向，结合平台特征(透镜三)和情绪联动(透镜四)
"""


